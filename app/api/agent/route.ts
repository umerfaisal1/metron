import { NextResponse } from 'next/server'
import { runMetronAgent } from '@/lib/agent/metronAgent'
import { AgentTaskRequest } from '@/lib/agent/types'
import { buildChartDataAndOption } from '@/lib/charts/aggregationEngine'
import { ProcessedChartData } from '@/lib/charts/types'

export async function POST(request: Request) {
  try {
    const body = (await request.json()) as AgentTaskRequest

    if (!body || !body.prompt) {
      return NextResponse.json(
        { error: 'Prompt is required for Metron Agent.' },
        { status: 400 }
      )
    }

    const agentResult = await runMetronAgent(body)

    let processedCharts: ProcessedChartData[] | undefined = undefined

    // If charts were generated by tool calling and we have spreadsheet data, process them into ECharts options
    if (agentResult.charts && agentResult.spreadsheet) {
      const { columns, data } = agentResult.spreadsheet
      processedCharts = agentResult.charts
        .map((rec) => {
          try {
            return buildChartDataAndOption(rec, columns, data)
          } catch (err) {
            console.warn('Failed to build chart option:', err)
            return null
          }
        })
        .filter((c): c is ProcessedChartData => c !== null)
    }

    return NextResponse.json({
      success: agentResult.success,
      message: agentResult.message,
      steps: agentResult.stepsExecuted,
      spreadsheet: agentResult.spreadsheet,
      charts: processedCharts,
    })
  } catch (err: unknown) {
    console.error('API /api/agent error:', err)
    return NextResponse.json(
      { error: err instanceof Error ? err.message : 'Agent execution failed' },
      { status: 500 }
    )
  }
}
